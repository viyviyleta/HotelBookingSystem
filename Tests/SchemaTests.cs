using System.Data.Common;
using Server.Database;
using Xunit;

namespace Tests;

/// <summary>
/// Требование 3 Части 1: структура созданной базы данных. Часть проверок смотрит в текст
/// DDL, который применяет сервер, часть — в каталог PostgreSQL уже созданной схемы,
/// то есть проверяется не намерение, а факт.
/// </summary>
public sealed class SchemaTests : IDisposable
{
    public void Dispose() => TestDatabase.Cleanup();

    // ------------------------------------------------------------------ Текст схемы

    [Fact]
    public void Schema_DeclaresFiveDomainTables()
    {
        Assert.Equal(5, CountOccurrences(DatabaseInitializer.Schema, "CREATE TABLE IF NOT EXISTS"));
        Assert.Contains("hotels", DatabaseInitializer.Schema);
        Assert.Contains("CREATE INDEX IF NOT EXISTS idx_bookings_room    ON bookings(room_id)",
            DatabaseInitializer.Schema);
        Assert.Contains("CREATE INDEX IF NOT EXISTS idx_payments_booking ON payments(booking_id)",
            DatabaseInitializer.Schema);
    }

    [Fact]
    public void Schema_DeclaresPrimaryAndForeignKeys()
    {
        Assert.Equal(5, CountOccurrences(DatabaseInitializer.Schema, "PRIMARY KEY"));
        Assert.Contains("hotel_id        INTEGER NOT NULL REFERENCES hotels(id) ON DELETE CASCADE",
            DatabaseInitializer.Schema);
        Assert.Contains("room_id        INTEGER NOT NULL REFERENCES rooms(id)", DatabaseInitializer.Schema);
        Assert.Contains("guest_id       INTEGER NOT NULL REFERENCES guests(id)", DatabaseInitializer.Schema);
        Assert.Contains("booking_id    INTEGER NOT NULL REFERENCES bookings(id)", DatabaseInitializer.Schema);
    }

    [Fact]
    public void Schema_DeclaresCheckConstraints()
    {
        Assert.Contains("CHECK (type IN ('Single', 'Double', 'Suite'))", DatabaseInitializer.Schema);
        Assert.Contains("CHECK (price_per_night > 0)", DatabaseInitializer.Schema);
        Assert.Contains("CHECK (total_amount >= 0)", DatabaseInitializer.Schema);
        Assert.Contains("CHECK (amount > 0)", DatabaseInitializer.Schema);
        Assert.Contains("CHECK (status IN ('Created', 'Paid', 'Cancelled'))", DatabaseInitializer.Schema);
        Assert.Contains("CHECK (check_out_date > check_in_date)", DatabaseInitializer.Schema);
    }

    [Fact]
    public void Schema_DeclaresUniqueConstraints()
    {
        Assert.Contains("UNIQUE (hotel_id, room_number)", DatabaseInitializer.Schema);
        Assert.Contains("email     TEXT    NOT NULL UNIQUE", DatabaseInitializer.Schema);
    }

    [Fact]
    public void Schema_UsesNativePostgresTypes()
    {
        // Номер и флаг занятости — честные BOOLEAN, деньги — фиксированная точность,
        // даты — timestamptz, идентификаторы событий генерирует база.
        Assert.Contains("is_available    BOOLEAN", DatabaseInitializer.Schema);
        Assert.Contains("is_successful BOOLEAN", DatabaseInitializer.Schema);
        Assert.Contains("NUMERIC(10,2)", DatabaseInitializer.Schema);
        Assert.Equal(3, CountOccurrences(DatabaseInitializer.Schema, "TIMESTAMPTZ"));
        Assert.Equal(2, CountOccurrences(DatabaseInitializer.Schema,
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
    }

    [Fact]
    public void Schema_DeclaresOneDeferredForeignKey()
    {
        // Тот самый случай «COMMIT невозможен»: проверка отложена до подтверждения.
        Assert.Equal(1, CountOccurrences(DatabaseInitializer.Schema, "DEFERRABLE INITIALLY DEFERRED"));
    }

    [Fact]
    public void Seed_DeclaresReferenceRowsAndIsRerunnable()
    {
        Assert.Contains("(101, 1, '101', 'Single', 100, TRUE)", DatabaseInitializer.Seed);
        Assert.Contains("(102, 1, '102', 'Double', 150, TRUE)", DatabaseInitializer.Seed);
        Assert.Contains("(201, 2, '201', 'Suite',  300, TRUE)", DatabaseInitializer.Seed);
        Assert.Equal(3, CountOccurrences(DatabaseInitializer.Seed, "ON CONFLICT (id) DO NOTHING"));
    }

    // ------------------------------------------------------- Каталог созданной базы

    [Fact]
    public void CreatedDatabase_ContainsFiveTables() =>
        Assert.Equal(5, CountInCatalog($"SELECT COUNT(*) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace " +
                                       "WHERE n.nspname = current_schema() AND c.relkind = 'r'"));

    [Fact]
    public void CreatedDatabase_EnforcesFourForeignKeysOfWhichOneIsDeferred()
    {
        Assert.Equal(4, CountInCatalog(ConstraintsOf('f')));
        Assert.Equal(1, CountInCatalog(ConstraintsOf('f', " AND condeferrable")));
    }

    [Fact]
    public void CreatedDatabase_HasPrimaryKeyAndCheckConstraintsOfEveryTable()
    {
        Assert.Equal(5, CountInCatalog(ConstraintsOf('p')));
        Assert.Equal(6, CountInCatalog(ConstraintsOf('c')));
    }

    [Fact]
    public void CreatedDatabase_FillsReferenceRows()
    {
        Assert.Equal(3, CountInCatalog("SELECT COUNT(*) FROM rooms"));
        Assert.Equal(2, CountInCatalog("SELECT COUNT(*) FROM hotels"));
        Assert.Equal(0, CountInCatalog("SELECT COUNT(*) FROM bookings"));
    }

    // oid схемы подбирается по её имени: поиск уже настроен на схему, которую создал тест.
    private const string SchemaOid = "(SELECT oid FROM pg_namespace WHERE nspname = current_schema())";

    private static string ConstraintsOf(char type, string extra = "") =>
        $"SELECT COUNT(*) FROM pg_constraint WHERE contype = '{type}' AND connamespace = {SchemaOid}{extra}";

    /// <summary>Счётчик из каталога PostgreSQL той самой схемы, что создал тест.</summary>
    private static int CountInCatalog(string sql)
    {
        TestDatabase.Create("catalog");

        using DbConnection connection = new HotelDatabase().Open();
        return Convert.ToInt32(HotelDatabase.Scalar(connection, null, sql) ?? 0);
    }

    private static int CountOccurrences(string text, string phrase)
    {
        int count = 0;

        for (int index = text.IndexOf(phrase, StringComparison.Ordinal);
             index >= 0;
             index = text.IndexOf(phrase, index + phrase.Length, StringComparison.Ordinal))
            count++;

        return count;
    }
}
